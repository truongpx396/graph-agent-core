"""The `TurnQueue` adapter (`app/ports/outbound/jobs.py`): Redis Streams as a persistent queue between the SSE-serving process and the agent workers
(GRAPH_PATTERNS.md pattern 43), so the two scale independently: more `uvicorn` processes for SSE connections, more workers for concurrent turns.

A job (`"turn"`, `"resume"` or `"cancel"`) uses two streams, never shared across jobs even on the same thread_id: `requests_stream_key(domain)`, one stream
per domain, read by the workers serving it as a consumer group (so no request is delivered twice), and `results_stream_key(request_id)`, written by
the worker, read here, and expired so an abandoned one cleans itself up.

This module is the PRODUCER half: submit, cancel, dedupe a resubmission, read the events back. Its only caller is the API
(`app/adapters/inbound/api/routers/chat.py`; the CLI and Telegram reach it over HTTP, specs/020). The CONSUMER half (the consumer group, the thread lock,
reclaim, dead letters) is the workers' (`app/adapters/inbound/workers/streams.py`). The module knows queue mechanics, not what a "turn" is.

Submission dedup (`claim_or_get_existing_submission`) closes the gap the workers' per-thread lock leaves: a retry arriving AFTER the first job finished
would run as a second independent turn.
"""
import asyncio
import json
import logging
import time
from collections.abc import AsyncGenerator
from typing import Any, cast

import redis.asyncio as redis

from app.core import metrics, spans
from app.core.errors import ErrorCode, ErrorEnvelope
from app.core.security import SecurityCtx
from app.platform.redis_client import UNAVAILABLE_ERRORS, StreamReadResponse, get_client
from app.ports.outbound.jobs import (
    CANCEL_FLAG_TTL_SECONDS,
    RESULTS_STREAM_TTL_SECONDS,
    TERMINAL_EVENT_TYPES,
    cancel_flag_key,
    request_thread_key,
    requests_stream_key,
    results_stream_key,
    thread_lock_key,
)

logger = logging.getLogger(__name__)


def encode_job(job: dict[str, Any]) -> str:
    """A job as it goes on a stream, with the W3C context of the request that published it, so the worker's spans join that request's trace
    (app/core/spans.py). Nothing is added when no request is being traced."""
    carrier = spans.carrier()
    return json.dumps({**job, spans.CARRIER_KEY: carrier} if carrier else job)


async def _remember_request_thread(client: redis.Redis, request_id: str, thread_id: str) -> None:
    """Before the job is published, so a client that reads the stream the moment it has the request id finds the owner. Its lifetime is the results stream's:
    the worker refreshes it with every event it publishes (`streams.py::publish_result`)."""
    await client.set(request_thread_key(request_id), thread_id, ex=RESULTS_STREAM_TTL_SECONDS)


async def thread_of_request(client: redis.Redis, request_id: str) -> str | None:
    value = await client.get(request_thread_key(request_id))
    return None if value is None else str(value)


async def publish_request(
    client: redis.Redis,
    *,
    request_id: str,
    text: str,
    thread_id: str,
    ctx: SecurityCtx,
    domain: str = "ecorp",
    require_approval: bool = False,
    images: list[str] | None = None,
    unattended: bool = False,
) -> None:
    """Producer side: enqueue one new-turn (`"kind": "turn"`) request onto `domain`'s requests stream; only a
    worker serving that domain reads it. `request_id` is generated by the CALLER
    (app/adapters/inbound/api/routers/chat.py) so it can listen on `results_stream_key(request_id)`
    before publishing, with no race against a fast worker. `images` (pattern 44) ride along as plain JSON
    strings (URLs/data URIs).

    `unattended` is for a caller with nobody to show an approval to (Telegram): the worker runs the turn
    through `astream_events_turn_unattended`, which declines a pause instead of forwarding it. It is a
    property of the JOB, not the worker, so it survives a reclaim (`republish_job` keeps the payload) and a
    crashed unattended turn is continued unattended.

    `enqueued_at` (epoch seconds) is stamped on every job the API publishes: the worker observes how long it waited (`agent_queue_wait_seconds`), and a job
    from an older API, with no stamp, is simply not observed. `republish_job` keeps it, so a reclaimed job's wait runs from its first publish.

    `domain` never rides in the payload; the stream it landed on says which domain it is for.
    `publish_resume_request`/`publish_cancel_request` use this SAME per-domain stream (dispatch-by-`kind` in
    agent_worker.py) and a resume/cancel MUST land on the same domain as the original turn, since the paused
    graph was built from that domain's tools; `X-Domain` keeps all three calls for one conversation aimed
    alike.
    """
    payload = encode_job(
        {
            "kind": "turn",
            "request_id": request_id,
            "text": text,
            "thread_id": thread_id,
            "ctx": ctx,
            "require_approval": require_approval,
            "images": images or [],
            "unattended": unattended,
            "enqueued_at": time.time(),
        }
    )
    await _remember_request_thread(client, request_id, thread_id)
    await client.xadd(requests_stream_key(domain), {"payload": payload})


async def publish_resume_request(
    client: redis.Redis,
    *,
    request_id: str,
    thread_id: str,
    approved: bool,
    ctx: SecurityCtx,
    domain: str = "ecorp",
) -> None:
    """Producer side: enqueue a resume decision for a turn paused at
    human_approval — the queued-path counterpart to
    `runtime/stream.py::astream_events_resume`. Any worker in `domain`'s
    pool can pick it up: the checkpoint lives in Postgres, not worker
    memory (see `publish_request`'s docstring for why `domain` must match
    the original turn's)."""
    payload = encode_job(
        {
            "kind": "resume",
            "request_id": request_id,
            "thread_id": thread_id,
            "approved": approved,
            "ctx": ctx,
            "enqueued_at": time.time(),
        }
    )
    await _remember_request_thread(client, request_id, thread_id)
    await client.xadd(requests_stream_key(domain), {"payload": payload})


async def publish_cancel_request(
    client: redis.Redis, *, request_id: str, thread_id: str, ctx: SecurityCtx, domain: str = "ecorp"
) -> None:
    """Producer side: enqueue a cancel for a turn paused at human_approval
    (queued-path counterpart to `runtime/stream.py::cancel_run`).
    Deliberately not how an ACTIVELY STREAMING turn gets cancelled — that's
    the cancel-flag mechanism below; this is a no-op in that case
    (`cancel_run` returns False). `POST /chat/cancel` always does both: set
    the flag AND publish this, so whichever mechanism applies handles it."""
    payload = encode_job(
        {"kind": "cancel", "request_id": request_id, "thread_id": thread_id, "ctx": ctx, "enqueued_at": time.time()}
    )
    await _remember_request_thread(client, request_id, thread_id)
    await client.xadd(requests_stream_key(domain), {"payload": payload})


async def set_cancel_flag(client: redis.Redis, thread_id: str) -> None:
    """Signal an ACTIVELY STREAMING `"turn"`/`"resume"` job's worker to stop at its
    next cancel-check (`runtime/stream.py::_iterate_with_timeout`'s
    `cancel_check`) — a short-lived flag, not a queued job, since that
    worker is polling this key directly, not waiting on the queue."""
    await client.set(cancel_flag_key(thread_id), "1", ex=CANCEL_FLAG_TTL_SECONDS)


async def is_thread_busy(client: redis.Redis, thread_id: str) -> bool:
    """Whether the conversation lock (`thread_lock_key`) exists: a worker took it for a running turn and has not released it. A read, never a write: the
    caller (a delete of the conversation) must not be the one to hold or free the lock."""
    return bool(await client.exists(thread_lock_key(thread_id)))


# --- A THIRD per-thread mechanism: submission dedup — closes a gap the
# thread lock above does NOT: that lock only rules out two jobs for the
# SAME thread_id running CONCURRENTLY. A double-submit (a client's own
# network-level retry, or a double-click) that arrives AFTER the first
# attempt already finished races nothing — the lock is free again, so the
# retry runs as a genuinely new, independent turn: a second LLM call, with
# its own fresh tool_call_ids, that can execute a real mutating tool call a
# SECOND time (app/core/tool_idempotency.py can't catch this either — its
# dedup is keyed by tool_call_id, and an independently-decided second turn
# never reuses the first's). `claim_or_get_existing_submission` closes that
# specific window: identical (thread_id, text, images) submitted twice
# within `ttl_seconds` reuses the FIRST attempt's own request_id instead of
# publishing a second `"turn"` job, so the retrying caller's SSE connection
# transparently gets that same turn's real events instead of either a
# duplicate execution or a bare THREAD_BUSY error.
def _submission_dedup_key(thread_id: str, digest: str) -> str:
    return f"chat:submit_dedup:{thread_id}:{digest}"


async def claim_or_get_existing_submission(
    client: redis.Redis, *, thread_id: str, digest: str, request_id: str, ttl_seconds: int
) -> tuple[str, bool]:
    """`digest` is the caller's own stable hash of whatever makes two
    submissions "the same" (text + images, for `POST /chat/stream/queued`)
    — this function doesn't compute it, just claims a slot for it.　Returns
    `(request_id_to_use, is_new_submission)`: the atomic `SET NX EX` either
    lands (this is the first submission this window has seen — proceed to
    publish a real job under `request_id`) or it doesn't (an identical
    submission already claimed this window — reuse ITS request_id, and the
    caller must NOT publish a second job).

    Narrow accepted race: if the key expires between this call's failed
    `SET` and its follow-up `GET` (a window of at most a few ms), this
    falls back to claiming it fresh under the caller's OWN `request_id`
    rather than looping — functionally identical to that key never having
    existed at all, just resolved on this call instead of forcing a retry.
    """
    key = _submission_dedup_key(thread_id, digest)
    claimed = bool(await client.set(key, request_id, nx=True, ex=ttl_seconds))
    if claimed:
        return request_id, True
    existing = await client.get(key)
    if existing is None:
        await client.set(key, request_id, ex=ttl_seconds)
        return request_id, True
    # decode_responses=True (get_client's own contract) means this is
    # always str at runtime; see StreamReadResponse's own comment on the
    # same redis-py stub-typing gap.
    return cast(str, existing), False


async def release_submission_claim(client: redis.Redis, *, thread_id: str, digest: str) -> None:
    """Compensating delete for a claim `claim_or_get_existing_submission`
    just won (`is_new_submission=True`) whose own job then failed to
    publish — app/adapters/inbound/api/routers/chat.py::chat_stream_queued's only caller. Without
    this, a claim can outlive the job it was meant to guard: the key
    keeps pointing at a `request_id` no job was ever published under, so
    any resubmission inside `ttl_seconds` gets `is_new=False` and streams
    a results stream nobody will ever write to (closed independently by
    `read_results`'s own `first_event_deadline_seconds`, but this avoids
    even reaching that path on the common failure). No-ops harmlessly if
    the key already expired or was never set — same "best-effort, never
    worth failing the caller over" posture as `delete_results_stream`.
    """
    try:
        await client.delete(_submission_dedup_key(thread_id, digest))
    except Exception as exc:  # noqa: BLE001 - cleanup is optional, never worth masking the original publish failure
        logger.warning("queue_submission_claim_release_failed", extra={"error_class": type(exc).__name__})


# One read is tried this many times before its error is raised, with a growing pause between tries. Only reads: see `UNAVAILABLE_ERRORS`.
READ_ATTEMPTS = 3
READ_RETRY_PAUSE_SECONDS = 0.2


async def read_events(client: redis.Redis, key: str, last_id: str, block_ms: int) -> StreamReadResponse:
    """`XREAD` from `last_id`, asked again after a connection error. Safe to repeat: it changes nothing, and `last_id` makes a repeat return exactly what
    the failed one would have (an `XADD` is not: a second copy of a `turn` job runs as a second turn once the first finishes, which is why redis-py's
    client-wide retry is not turned on). A Redis blip used to end every open SSE response at once (pattern 43). Shared with `ingest_queue.py`'s reader."""
    for attempt in range(1, READ_ATTEMPTS + 1):
        try:
            return cast(StreamReadResponse, await client.xread({key: last_id}, block=block_ms, count=10))
        except UNAVAILABLE_ERRORS as exc:
            metrics.agent_worker_queue_read_failed_total.labels(queue="results").inc()
            if attempt == READ_ATTEMPTS:
                raise
            logger.warning("queue_results_read_retried", extra={"attempt": attempt, "error_class": type(exc).__name__})
            await asyncio.sleep(READ_RETRY_PAUSE_SECONDS * attempt)
    raise AssertionError("unreachable")  # pragma: no cover - the loop returns or raises on its last attempt


async def read_results(
    client: redis.Redis,
    request_id: str,
    *,
    block_ms: int = 5000,
    first_event_deadline_seconds: float | None = None,
) -> AsyncGenerator[dict[str, Any], None]:
    """The events of `read_results_from`, without their positions: for a caller that reads a turn once, start to end."""
    async for _entry_id, event in read_results_from(
        client, request_id, block_ms=block_ms, first_event_deadline_seconds=first_event_deadline_seconds
    ):
        yield event


async def read_results_from(
    client: redis.Redis,
    request_id: str,
    *,
    after: str = "0",
    block_ms: int = 5000,
    first_event_deadline_seconds: float | None = None,
) -> AsyncGenerator[tuple[str, dict[str, Any]], None]:
    """Producer side: yield each event published for `request_id`, in order, blocking up to `block_ms` per read,
    until a terminal event (`type` is `done`, `error` or `approval_required`). `approval_required` is terminal
    because it is the last event `_run_graph_stream` yields for a paused turn and the worker stops forwarding
    right after it; resuming is a SEPARATE job with its own results stream, so without this the generator
    would wait forever for a done/error a paused worker never sends. A caller that stops iterating early
    leaves the stream to expire via TTL.

    `first_event_deadline_seconds` bounds ONLY the wait for the FIRST event, not the job. Without it `if not
    response: continue` loops forever when nobody will ever publish (no agent-worker for this domain, or a
    submission-dedup claim pointing at a request_id whose publish failed; see the compensating delete in
    app/adapters/inbound/api/routers/chat.py), silently hanging an open SSE connection. Once a real event arrives the deadline
    is cleared, so a legitimately long job (bounded by its own worker-side timeout, or not at all for ingest)
    is never cut short. On expiry it yields one `error` event, the same terminal shape a worker-reported
    failure has, and returns.
    """
    key = results_stream_key(request_id)
    last_id = after
    # Only from the start: a client resuming from a position has already seen the job run, so a quiet stretch is a tool, not a job nobody picked up.
    deadline = (
        time.monotonic() + first_event_deadline_seconds
        if first_event_deadline_seconds is not None and after == "0"
        else None
    )
    while True:
        if deadline is not None and time.monotonic() >= deadline:
            # Nobody picked this job up. Counted so a total outage — which is a
            # stream of these, one per request — can be alerted on
            # (WorkerUnreachable, observability/prometheus/alerts.yml).
            metrics.agent_worker_unreachable_total.labels(queue="agent").inc()
            envelope = ErrorEnvelope(
                code=ErrorCode.WORKER_UNREACHABLE,
                message=(
                    f"No response for {request_id!r} after "
                    f"{first_event_deadline_seconds:.0f}s — is an agent-worker "
                    "running for this domain?"
                ),
            )
            yield last_id, {"type": "error", "content": envelope.message, **envelope.to_dict()}
            return
        response = await read_events(client, key, last_id, block_ms)
        if not response:
            continue  # no new entries within block_ms — poll again
        deadline = None  # a real event arrived — no longer "nobody is listening"
        _, entries = response[0]
        for entry_id, fields in entries:
            last_id = entry_id
            event = json.loads(fields["payload"])
            yield entry_id, event
            if event.get("type") in TERMINAL_EVENT_TYPES:
                return


async def delete_results_stream(client: redis.Redis, request_id: str) -> None:
    """Best-effort cleanup once the producer has consumed a terminal event —
    not required for correctness (TTL already bounds a leaked stream's
    lifetime), just avoids waiting out the full TTL on the common path."""
    try:
        await client.delete(results_stream_key(request_id))
    except Exception as exc:  # noqa: BLE001 - cleanup is optional, never worth failing a turn over
        logger.warning("queue_results_cleanup_failed", extra={"error_class": type(exc).__name__})


class RedisTurnQueue:
    """The `TurnQueue` adapter. The module's functions are looked up at call time, which is how their tests patch `get_client`."""

    async def claim_or_get_existing_submission(self, *, thread_id: str, digest: str, request_id: str, ttl_seconds: int) -> tuple[str, bool]:
        return await claim_or_get_existing_submission(get_client(), thread_id=thread_id, digest=digest, request_id=request_id, ttl_seconds=ttl_seconds)

    async def release_submission_claim(self, *, thread_id: str, digest: str) -> None:
        await release_submission_claim(get_client(), thread_id=thread_id, digest=digest)

    async def publish_request(
        self,
        *,
        request_id: str,
        text: str,
        thread_id: str,
        ctx: SecurityCtx,
        domain: str = "ecorp",
        require_approval: bool = False,
        images: list[str] | None = None,
        unattended: bool = False,
    ) -> None:
        await publish_request(
            get_client(), request_id=request_id, text=text, thread_id=thread_id, ctx=ctx, domain=domain,
            require_approval=require_approval, images=images, unattended=unattended,
        )

    async def publish_resume_request(self, *, request_id: str, thread_id: str, approved: bool, ctx: SecurityCtx, domain: str = "ecorp") -> None:
        await publish_resume_request(get_client(), request_id=request_id, thread_id=thread_id, approved=approved, ctx=ctx, domain=domain)

    async def publish_cancel_request(self, *, request_id: str, thread_id: str, ctx: SecurityCtx, domain: str = "ecorp") -> None:
        await publish_cancel_request(get_client(), request_id=request_id, thread_id=thread_id, ctx=ctx, domain=domain)

    async def set_cancel_flag(self, thread_id: str) -> None:
        await set_cancel_flag(get_client(), thread_id)

    async def is_thread_busy(self, thread_id: str) -> bool:
        return await is_thread_busy(get_client(), thread_id)

    async def read_results(self, request_id: str, *, first_event_deadline_seconds: float | None = None) -> AsyncGenerator[dict[str, Any], None]:
        async for event in read_results(get_client(), request_id, first_event_deadline_seconds=first_event_deadline_seconds):
            yield event

    async def read_results_from(
        self, request_id: str, *, after: str = "0", first_event_deadline_seconds: float | None = None
    ) -> AsyncGenerator[tuple[str, dict[str, Any]], None]:
        async for entry_id, event in read_results_from(get_client(), request_id, after=after, first_event_deadline_seconds=first_event_deadline_seconds):
            yield entry_id, event

    async def thread_of_request(self, request_id: str) -> str | None:
        return await thread_of_request(get_client(), request_id)

    async def ping(self) -> None:
        await get_client().ping()
